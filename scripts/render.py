"""Render approved source excerpts or explicitly labeled original-design reservations."""
from __future__ import annotations
import argparse
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib,json
from core import ROOT,assert_valid,binary,load,run,probe,fingerprint,write_json,sha,usable_clip
from design import plate,archive_overlay,fonts
from captions import export

def render_cut(db,name,out,mode='animatic',height=None,root=ROOT):
    assert_valid(db,root,release=mode=='final')
    fonts();cut=db['timeline']['cuts'][name];fps=db['timeline']['fps']
    h=height or cut['height'];w=round(cut['width']*h/cut['height']/2)*2
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    cache=Path(root)/'work/render'/f'{mode}-{name}-{w}x{h}';cache.mkdir(parents=True,exist_ok=True)
    clips={x['clip_id']:x for x in db['clips']}
    actual=[]
    for s in cut['segments']:
        s=s.copy()
        if mode=='animatic' and s['kind']=='clip':s['kind']='placeholder'
        if mode=='rough' and s['kind'] in ['placeholder','clip']:
            c=clips[s['clip_id']]
            good=not usable_clip(c,db,root) and c['source_out_ms']-c['source_in_ms']==s['duration_ms']
            s['kind']='clip' if good else 'placeholder'
        actual.append(s)
    cut={**cut,'segments':actual}
    def segment(s):
        dur=s['duration_ms']/1000;frames=round(dur*fps)
        key=hashlib.sha256(json.dumps(s,sort_keys=True).encode()+fingerprint(db,root)['input_sha256'].encode()).hexdigest()[:16]
        png=cache/f'{s["segment_id"]}-{key}.png';dest=cache/f'{s["segment_id"]}-{key}.mkv'
        if dest.exists():return dest
        args=[binary('ffmpeg'),'-hide_banner','-loglevel','error','-y']
        if s['kind']=='clip':
            c=clips[s['clip_id']];media=root/c['media_path'];info=probe(media)
            archive_overlay(s,w,h,png,mode)
            args+=['-ss',str(c['source_in_ms']/1000),'-i',media,'-loop','1','-i',png]
            video=f'[0:v]fps={fps},scale={w}:{h}:force_original_aspect_ratio=decrease,pad={w}:{h}:(ow-iw)/2:(oh-ih)/2,setsar=1,trim=duration={dur},setpts=PTS-STARTPTS[v];[v][1:v]overlay=shortest=1[outv]'
            if any(s['codec_type']=='audio' for s in info['streams']):
                audio=f'[0:a]aresample=48000,aformat=channel_layouts=stereo,apad,atrim=duration={dur},asetpts=PTS-STARTPTS[outa]'
            else:audio=f'anullsrc=r=48000:cl=stereo,atrim=duration={dur}[outa]'
            args+=['-filter_complex',video+';'+audio,'-map','[outv]','-map','[outa]']
        else:
            plate(s,w,h,png,mode)
            args+=['-loop','1','-framerate',str(fps),'-i',png,'-f','lavfi','-i','anullsrc=r=48000:cl=stereo']
            vf=f"zoompan=z='1+0.008*on/{max(1,frames-1)}':x='iw/2-iw/zoom/2':y='ih/2-ih/zoom/2':d=1:s={w}x{h}:fps={fps}"
            # Short fades are inside each edit reservation, never extra time.
            vf+=f',fade=t=in:st=0:d=0.8,fade=t=out:st={max(0,dur-.8)}:d=0.8,setsar=1'
            args+=['-vf',vf,'-map','0:v','-map','1:a']
        args+=['-t',str(dur),'-r',str(fps),'-c:v','libx264','-preset','veryfast','-crf','22','-pix_fmt','yuv420p','-threads','2','-c:a','pcm_s16le','-ar','48000','-ac','2',dest]
        run(args)
        print(f'{name}: {s["segment_id"]} {dur:g}s {s["kind"]}',flush=True)
        return dest
    with ThreadPoolExecutor(max_workers=2) as pool:parts=list(pool.map(segment,actual))
    # ffconcat syntax: paths generated by us; quote apostrophes explicitly.
    listing=cache/'concat.txt'
    listing.write_text('\n'.join("file '"+p.resolve().as_posix().replace("'","'\\''")+"'" for p in parts),encoding='utf-8')
    filename={'master':'master_4k.mp4' if h==2160 else 'master_1080p.mp4' if h==1080 else f'master_{h}p.mp4','trailer':'trailer_90s.mp4','vertical':'vertical_60s.mp4'}[name]
    dest=out/filename
    # Recheck immediately before producing any unwatermarked artifact.
    if mode=='final':assert_valid(db,root,True)
    args=[binary('ffmpeg'),'-hide_banner','-loglevel','error','-y','-f','concat','-safe','0','-i',listing,'-t',str(cut['duration_ms']/1000),'-c:v','copy','-c:a','aac','-b:a','192k','-ar','48000','-ac','2']
    if mode=='final' and any(s['kind']=='clip' for s in actual):
        import subprocess,re
        measure=subprocess.run([binary('ffmpeg'),'-hide_banner','-f','concat','-safe','0','-i',str(listing),'-af','loudnorm=I=-16:TP=-1:LRA=11:print_format=json','-vn','-f','null','-'],capture_output=True,text=True,encoding='utf-8',errors='replace')
        if measure.returncode:raise RuntimeError('Loudness measurement failed')
        matches=re.findall(r'\{[^{}]*"input_i"[^{}]*\}',measure.stderr,re.S)
        if not matches:raise ValueError('Loudness measurement absent')
        loud=json.loads(matches[-1])
        if any(loud[k] in ['-inf','inf'] for k in ['input_i','input_tp','input_lra','input_thresh']):raise ValueError('Source-audio final cannot normalize an entirely silent mix')
        af=f'loudnorm=I=-16:TP=-1:LRA=11:measured_I={loud["input_i"]}:measured_TP={loud["input_tp"]}:measured_LRA={loud["input_lra"]}:measured_thresh={loud["input_thresh"]}:offset={loud["target_offset"]}:linear=true'
        args+=['-af',af]
        write_json(out/f'{name}_loudness_pass1.json',loud)
    args+=['-movflags','+faststart',dest]
    run(args)
    stem='captions_en' if name=='master' else name+'_captions_en'
    cues=export(cut,db,out,stem,mode)
    write_json(out/f'{name}_render.json',{'mode':mode,'cut':name,'duration_ms':cut['duration_ms'],'width':w,'height':h,'fps':fps,'audio':'source audio where verified; silence elsewhere' if mode!='animatic' else 'intentional silence','input_sha256':fingerprint(db,root)['input_sha256'],'video_sha256':sha(dest),'segments':[{'segment_id':s['segment_id'],'kind':s['kind']} for s in actual],'captions':len(cues)})
    return dest

def main():
    p=argparse.ArgumentParser();p.add_argument('mode',choices=['animatic','rough']);p.add_argument('--cut',choices=['master','trailer','vertical']);p.add_argument('--height',type=int);a=p.parse_args()
    db=load();assert_valid(db)
    if a.height and (a.height<120 or a.height%2):p.error('height must be even and at least 120')
    out=ROOT/'outputs'/('animatic' if a.mode=='animatic' else 'rough_cut')
    for name in ([a.cut] if a.cut else db['timeline']['cuts']):print(render_cut(db,name,out,a.mode,a.height),flush=True)
    from build_timeline import reports
    reports(db,out,a.mode)

if __name__=='__main__':main()
